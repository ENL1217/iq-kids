#!/usr/bin/env node
// tools/build-manifest.mjs
// 掃 questions/<topic>/<difficulty>/*.json 自動產生 questions/manifest.json。
// 用法: node tools/build-manifest.mjs

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOPICS, DIFFICULTIES } from './lib.mjs';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = join(__dirname, '..');
const QUESTIONS_DIR = join(ROOT, 'questions');

async function listIds(topic, difficulty) {
  const dir = join(QUESTIONS_DIR, topic, difficulty);
  let entries;
  try {
    entries = await readdir(dir);
  } catch (e) {
    if (e.code === 'ENOENT') return [];
    throw e;
  }
  const ids = [];
  for (const name of entries) {
    if (!name.endsWith('.json')) continue;
    if (name === '.gitkeep' || name === 'manifest.json') continue;
    const id = basename(name, '.json');
    // 簡單驗證 id 開頭
    if (!id.startsWith(`${topic}-${difficulty}-`)) {
      console.warn(`[build-manifest] WARN: ${relative(ROOT, join(dir, name))} id doesn't match folder (${id})`);
      continue;
    }
    ids.push(id);
  }
  ids.sort();  // 字典序,000 在前
  return ids;
}

(async () => {
  const topics = {};
  let total = 0;
  for (const t of TOPICS) {
    topics[t] = {};
    for (const d of DIFFICULTIES) {
      const ids = await listIds(t, d);
      topics[t][d] = ids;
      total += ids.length;
    }
  }

  const manifest = {
    version: 1,
    generated_at: new Date().toISOString(),
    _comment: "This file is auto-generated by tools/build-manifest.mjs. Don't edit by hand.",
    topics
  };

  const outPath = join(QUESTIONS_DIR, 'manifest.json');
  await writeFile(outPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  console.log(`[build-manifest] wrote ${relative(ROOT, outPath)}`);
  console.log(`  total: ${total} questions`);
  for (const t of TOPICS) {
    const counts = DIFFICULTIES.map(d => `${d}=${topics[t][d].length}`).join(' ');
    console.log(`  ${t.padEnd(10)} ${counts}`);
  }
})();
